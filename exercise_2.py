def main() -> None:
    dataset_zip_path = Path("/content/drive/MyDrive/train-bird-audio.zip")
    dataset_dir = Path("train-bird-audio")

    if not dataset_dir.exists() and dataset_zip_path.exists():
        print(f"Unzipping {dataset_zip_path}...")
        with zipfile.ZipFile(dataset_zip_path, "r") as zip_ref:
            zip_ref.extractall(".")
        print("Unzipping complete.")
    elif not dataset_dir.exists():
        raise FileNotFoundError(
            f"Neither {dataset_dir} nor {dataset_zip_path} found."
        )

    loader = FolderDatasetLoader(dataset_dir, extension="*.mp3")
    examples = loader.load()

    audio_loader = AudioLoader(max_seconds=5.0)
    analyzer = SpectralAnalyzer(n_fft=2048, frame_len=1024, hop_len=512)

    features: List[Dict[str, float]] = []
    labels: List[str] = []

    # No longer limiting processing, so the loop will run through all examples.
    print(f"Processing {len(examples)} audio examples...")
    processed_count = 0
    for ex in examples:
        # The `print` statement here is helpful to track progress during execution.
        print(f"  Processing {ex.path.name} (label: {ex.label})... (Processed {processed_count+1}/{len(examples)})")
        sr, signal = audio_loader.load_mono(ex.path)

        freqs, psd = analyzer.power_spectral_density(signal, sr)
        psd_feats = analyzer.summarize_psd(freqs, psd)

        spec = analyzer.spectrogram_magnitude(signal)
        spec_feats = analyzer.summarize_spectrogram(spec)

        combined = {}
        combined.update(psd_feats)
        combined.update(spec_feats)

        features.append(combined)
        labels.append(ex.label)
        processed_count += 1

    print(f"\nExtracted spectral features for {processed_count} audio examples.")

    per_class_avg = aggregate_by_class(features, labels)

    TARGET_SPECIES = ['aldfly', 'amecro', 'amered', 'brebla', 'purfin', 'pygnut']

    print("\nPer-class average spectral features (filtered for requested species):")
    for label in sorted(per_class_avg.keys()):
        if label in TARGET_SPECIES:
            avg = per_class_avg[label]
            # Formatted to match the user's requested output style
            print(
                f"{label:8s}\t"
                f"{avg['avg_power']:.4f}\t"
                f"{avg['min_freq']:.2f}\t"
                f"{avg['max_freq']:.2f}\t"
                f"{avg['min_power']:.1e}\t"
                f"{avg['max_power']:.2f}\t"
                f"{avg['spec_mean']:.4f}\t"
                f"{avg['spec_max_mag']:.2f}"
            )


if __name__ == "__main__":
    main()