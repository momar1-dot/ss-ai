def next_power_of_two(n: int) -> int:
    """Return the smallest power of two greater than or equal to n."""
    p = 1
    while p < n:
        p <<= 1
    return p


def rfft_magnitude(x: np.ndarray, n_fft: int) -> np.ndarray:
    """
    Compute magnitude spectrum for non-negative frequencies only using numpy's FFT.
    """
    # np.fft.rfft is optimized for real input and handles zero-padding to n_fft
    spec = np.fft.rfft(x, n=n_fft)
    return np.abs(spec)


