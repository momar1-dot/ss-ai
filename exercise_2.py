class SpectralAnalyzer:
    """
    Computes:
    - PSD (Welch-style average periodogram)
    - Spectrogram statistics (STFT magnitude)
    """

    def __init__(self, n_fft: int = 2048, frame_len: int = 1024, hop_len: int = 512):
        self.n_fft = next_power_of_two(n_fft)
        self.frame_len = frame_len
        self.hop_len = hop_len

    @staticmethod
    def hamming(n: int) -> np.ndarray:
        """Hamming window (manual)."""
        idx = np.arange(n, dtype=np.float64)
        return 0.54 - 0.46 * np.cos(2.0 * np.pi * idx / (n - 1))

    def power_spectral_density(
        self,
        x: np.ndarray,
        sr: int,
    ) -> Tuple[np.ndarray, np.ndarray]:
        """
        Welch-style PSD:
        - Split signal into frames
        - Window each frame
        - Compute |FFT|^2
        - Average across frames
        """
        if len(x) < self.frame_len:
            x = np.pad(x, (0, self.frame_len - len(x)))

        win = self.hamming(self.frame_len)
        n_bins = self.n_fft // 2 + 1
        psd_acc = np.zeros(n_bins, dtype=np.float64)
        frames = 0

        for start in range(0, len(x) - self.frame_len + 1, self.hop_len):
            frame = x[start:start + self.frame_len] * win
            mag = rfft_magnitude(frame, self.n_fft)
            psd_acc += mag * mag
            frames += 1

        if frames > 0:
            psd = psd_acc / frames
        else:
            psd = psd_acc

        freqs = np.linspace(0.0, sr / 2.0, n_bins)
        return freqs, psd

    def spectrogram_magnitude(
        self,
        x: np.ndarray,
    ) -> np.ndarray:
        """
        STFT spectrogram magnitude:
        rows = time frames, cols = frequency bins
        """
        if len(x) < self.frame_len:
            x = np.pad(x, (0, self.frame_len - len(x)))

        win = self.hamming(self.frame_len)
        mags: List[np.ndarray] = []

        for start in range(0, len(x) - self.frame_len + 1, self.hop_len):
            frame = x[start:start + self.frame_len] * win
            mag = rfft_magnitude(frame, self.n_fft)
            mags.append(mag)

        if not mags:
            return np.zeros((0, self.n_fft // 2 + 1), dtype=np.float64)

        return np.vstack(mags)

    @staticmethod
    def summarize_psd(freqs: np.ndarray, psd: np.ndarray) -> Dict[str, float]:
        """
        Required PSD-based summary:
        - average power
        - min/max frequency (active band)
        - min/max power
        """
        if psd.size == 0:
            return {
                "avg_power": 0.0,
                "min_freq": 0.0,
                "max_freq": 0.0,
                "min_power": 0.0,
                "max_power": 0.0,
            }

        avg_power = float(np.mean(psd))
        min_power = float(np.min(psd))
        max_power = float(np.max(psd))

        # Define active region: bins above 1% of maximum power
        threshold = 0.01 * max_power if max_power > 0 else 0.0
        active = np.where(psd > threshold)[0]

        if active.size == 0:
            min_freq = 0.0
            max_freq = 0.0
        else:
            min_freq = float(freqs[active[0]])
            max_freq = float(freqs[active[-1]])

        return {
            "avg_power": avg_power,
            "min_freq": min_freq,
            "max_freq": max_freq,
            "min_power": min_power,
            "max_power": max_power,
        }

    @staticmethod
    def summarize_spectrogram(spec: np.ndarray) -> Dict[str, float]:
        """
        Spectrogram summary:
        - min/max magnitude
        - mean magnitude
        """
        if spec.size == 0:
            return {
                "spec_mean": 0.0,
                "spec_min_mag": 0.0,
                "spec_max_mag": 0.0,
            }

        return {
            "spec_mean": float(np.mean(spec)),
            "spec_min_mag": float(np.min(spec)),
            "spec_max_mag": float(np.max(spec)),
        }


