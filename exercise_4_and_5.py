class TimeDomainFeatureExtractor:
    """Computes time-domain statistics (Task 2)."""

    @staticmethod
    def extract(x: np.ndarray) -> Dict[str, float]:
        if x.size == 0:
            return {
                "rms": 0.0,
                "std": 0.0,
                "crest": 0.0,
                "avg_amp": 0.0,
            }

        rms = float(np.sqrt(np.mean(x * x)))
        peak = float(np.max(np.abs(x)))
        crest = peak / rms if rms != 0.0 else 0.0

        return {
            "rms": rms,
            "std": float(np.std(x)),
            "crest": crest,
            "avg_amp": float(np.mean(np.abs(x))),
        }


class FeatureExtractor:
    """Combines time and fast frequency-domain features."""

    def __init__(self, spectral: FastSpectralFeatures) -> None:
        self.spectral = spectral

    def extract(self, x: np.ndarray, sr: int) -> Dict[str, float]:
        feats: Dict[str, float] = {}
        feats.update(TimeDomainFeatureExtractor.extract(x))
        feats.update(self.spectral.extract(x, sr))
        return feats


def dicts_to_matrix(rows: List[Dict[str, float]]) -> Tuple[np.ndarray, List[str]]:
    """Convert feature dicts to feature matrix X."""
    names = sorted(rows[0].keys())
    mat = np.array([[row[n] for n in names] for row in rows], dtype=np.float64)
    return mat, names


