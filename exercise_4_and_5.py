def main() -> None:
    set_seed(SEED)

    dataset_zip_path = Path("/content/drive/MyDrive/train-bird-audio.zip")
    dataset_dir = Path("train-bird-audio")

    if not dataset_dir.exists() and dataset_zip_path.exists():
        print(f"Unzipping {dataset_zip_path}...")
        with zipfile.ZipFile(dataset_zip_path, "r") as zip_ref:
            zip_ref.extractall(".")
        print("Unzipping complete.")
    elif not dataset_dir.exists():
        raise FileNotFoundError(
            f"Neither {dataset_dir} nor {dataset_zip_path} found."
        )

    # Speed: limit files per class and shorten audio
    loader = FolderDatasetLoader(
        dataset_dir=dataset_dir,
        extension="*.mp3",
        max_files_per_class=60,
    )
    examples = loader.load()

    audio_loader = AudioLoader(max_seconds=5.0, downsample_to=16000)
    spectral = FastSpectralFeatures(n_fft=2048)
    extractor = FeatureExtractor(spectral=spectral)

    feature_rows: List[Dict[str, float]] = []
    labels: List[str] = []

    for ex in examples:
        sr, x = audio_loader.load_mono(ex.path)
        feature_rows.append(extractor.extract(x, sr))
        labels.append(ex.label)

    x_mat, _ = dicts_to_matrix(feature_rows)

    x_train, x_test, y_train, y_test = train_test_split(
        x_mat,
        labels,
        test_size=0.2,
        random_state=SEED,
        stratify=labels if len(set(labels)) > 1 else None,
    )

    clf = BirdClassifier(seed=SEED)
    clf.fit(x_train, y_train)

    y_pred = clf.predict(x_test)
    print_metrics(y_test, y_pred)


if __name__ == "__main__":
    main()

