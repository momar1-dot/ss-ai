class AudioLoader:
    """
    Loads audio into mono signals.

    Speed controls:
    - max_seconds truncates audio (e.g., 5 seconds)
    - downsample_to reduces sample rate by simple decimation (no resampling libs)
      Only safe if original sr is a multiple of downsample_to.
    """

    def __init__(
        self,
        max_seconds: float = 5.0,
        downsample_to: int = 16000,
    ) -> None:
        self.max_seconds = max_seconds
        self.downsample_to = downsample_to

    def load_mono(self, path: Path) -> Tuple[int, np.ndarray]:
        """Load audio file as mono float64 signal (optionally downsampled)."""
        data, sr = sf.read(str(path), dtype="float64", always_2d=True)
        mono = data.mean(axis=1)

        mono = mono[: int(sr * self.max_seconds)]
        mono = mono - float(np.mean(mono))  # remove DC

        mono, sr = self._downsample_if_possible(mono, sr)
        return sr, mono

    def _downsample_if_possible(self, x: np.ndarray, sr: int) -> Tuple[np.ndarray, int]:
        """Downsample by integer factor if possible (fast decimation)."""
        if sr <= self.downsample_to:
            return x, sr

        factor = sr // self.downsample_to
        if factor <= 1:
            return x, sr

        if sr % self.downsample_to != 0:
            # If not divisible, skip downsampling for correctness
            return x, sr

        return x[::factor], sr // factor


# ----------------------------
# FFT (from scratch, radix-2)
# ----------------------------

def next_power_of_two(n: int) -> int:
    """Return the smallest power of two >= n."""
    p = 1
    while p < n:
        p <<= 1
    return p


def fft_recursive(x: np.ndarray) -> np.ndarray:
    """Recursive radix-2 FFT. Input length must be a power of two."""
    n = len(x)
    if n == 1:
        return x

    even = fft_recursive(x[0::2])
    odd = fft_recursive(x[1::2])

    out = np.zeros(n, dtype=np.complex128)
    for k in range(n // 2):
        angle = -2.0 * np.pi * k / n
        w = complex(np.cos(angle), np.sin(angle))
        t = w * odd[k]
        out[k] = even[k] + t
        out[k + n // 2] = even[k] - t

    return out


def rfft_power(x: np.ndarray, n_fft: int) -> np.ndarray:
    """Return power spectrum for non-negative frequencies."""
    n_fft = next_power_of_two(n_fft)

    sig = np.zeros(n_fft, dtype=np.complex128)
    length = min(len(x), n_fft)
    sig[:length] = x[:length].astype(np.complex128)

    spec = fft_recursive(sig)
    half = n_fft // 2 + 1
    mag = np.abs(spec[:half])
    return mag * mag


