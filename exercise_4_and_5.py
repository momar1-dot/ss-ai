class ExplainabilityReporter:
    """
    Generates explainability outputs for a trained RandomForest model.

    Outputs:
    - Model-specific impurity-based importance (feature_importances_)
    - Permutation importance on test set
    """

    def __init__(self, feature_names: List[str]) -> None:
        self.feature_names = feature_names

    def report_model_importance(
        self,
        model: RandomForestClassifier,
        top_k: int = 12,
    ) -> None:
        """Print top-k model-specific feature importances."""
        importances = model.feature_importances_
        order = np.argsort(importances)[::-1]

        print("\nExplainability: model-specific feature importance (RandomForest)")
        for idx in order[:top_k]:
            name = self.feature_names[idx]
            score = float(importances[idx])
            print(f"- {name:16s} {score:.6f}")

    def report_permutation_importance(
        self,
        model: RandomForestClassifier,
        x_test: np.ndarray,
        y_test: List[str],
        seed: int,
        top_k: int = 12,
    ) -> None:
        """
        Permutation importance:
        Measures performance drop when shuffling a single feature.
        """
        result = permutation_importance(
            model,
            x_test,
            y_test,
            n_repeats=10,
            random_state=seed,
            n_jobs=-1,
        )

        importances = result.importances_mean
        order = np.argsort(importances)[::-1]

        print("\nExplainability: permutation importance (test set)")
        for idx in order[:top_k]:
            name = self.feature_names[idx]
            score = float(importances[idx])
            print(f"- {name:16s} {score:.6f}")


