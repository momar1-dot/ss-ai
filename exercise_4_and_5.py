class BirdClassifier:
    """Random Forest classifier (fast + robust)."""

    def __init__(self, seed: int) -> None:
        self.model = RandomForestClassifier(
            n_estimators=250,
            random_state=seed,
            n_jobs=-1,
        )

    def fit(self, x_train: np.ndarray, y_train: List[str]) -> None:
        self.model.fit(x_train, y_train)

    def predict(self, x_test: np.ndarray) -> List[str]:
        return list(self.model.predict(x_test))


def print_metrics(y_true: List[str], y_pred: List[str]) -> None:
    acc = accuracy_score(y_true, y_pred)
    prec, rec, f1, _ = precision_recall_fscore_support(
        y_true,
        y_pred,
        average="macro",
        zero_division=0,
    )

    print(f"Accuracy : {acc:.4f}")
    print(f"Precision: {prec:.4f} (macro)")
    print(f"Recall   : {rec:.4f} (macro)")
    print(f"F1-score : {f1:.4f} (macro)\n")

    print("Classification report:")
    print(classification_report(y_true, y_pred, zero_division=0))


