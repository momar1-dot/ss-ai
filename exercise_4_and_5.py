class FastSpectralFeatures:
    """
    Computes fast frequency-domain features from a single windowed FFT.

    Features:
    - avg_power
    - min_power
    - max_power
    - min_freq / max_freq of active band (PSD > 1% max)
    - band powers: energy in fixed frequency bands (bird vocal ranges)
    """

    def __init__(self, n_fft: int = 2048) -> None:
        self.n_fft = next_power_of_two(n_fft)

    @staticmethod
    def hamming(n: int) -> np.ndarray:
        idx = np.arange(n, dtype=np.float64)
        return 0.54 - 0.46 * np.cos(2.0 * np.pi * idx / (n - 1))

    def extract(self, x: np.ndarray, sr: int) -> Dict[str, float]:
        if x.size == 0:
            return self._zeros()

        frame_len = min(len(x), self.n_fft)
        frame = x[:frame_len].copy()

        if frame_len < self.n_fft:
            frame = np.pad(frame, (0, self.n_fft - frame_len))

        frame *= self.hamming(self.n_fft)

        psd = rfft_power(frame, self.n_fft)
        freqs = np.linspace(0.0, sr / 2.0, len(psd))

        max_power = float(np.max(psd))
        threshold = 0.01 * max_power if max_power > 0 else 0.0
        active = np.where(psd > threshold)[0]

        if active.size == 0:
            min_freq = 0.0
            max_freq = 0.0
        else:
            min_freq = float(freqs[active[0]])
            max_freq = float(freqs[active[-1]])

        feats = {
            "avg_power": float(np.mean(psd)),
            "min_power": float(np.min(psd)),
            "max_power": max_power,
            "min_freq": min_freq,
            "max_freq": max_freq,
        }

        feats.update(self._band_powers(freqs, psd))
        return feats

    def _band_powers(self, freqs: np.ndarray, psd: np.ndarray) -> Dict[str, float]:
        """
        Band powers chosen to match typical bird vocalization regions.
        Adjust if your Task 3 results suggest different bands.
        """
        bands = [
            ("p_0_500", 0.0, 500.0),
            ("p_500_1500", 500.0, 1500.0),
            ("p_1500_3000", 1500.0, 3000.0),
            ("p_3000_6000", 3000.0, 6000.0),
            ("p_6000_10000", 6000.0, 10000.0),
        ]

        out: Dict[str, float] = {}
        for name, lo, hi in bands:
            idx = np.where((freqs >= lo) & (freqs < hi))[0]
            out[name] = float(np.mean(psd[idx])) if idx.size else 0.0
        return out

    @staticmethod
    def _zeros() -> Dict[str, float]:
        return {
            "avg_power": 0.0,
            "min_power": 0.0,
            "max_power": 0.0,
            "min_freq": 0.0,
            "max_freq": 0.0,
            "p_0_500": 0.0,
            "p_500_1500": 0.0,
            "p_1500_3000": 0.0,
            "p_3000_6000": 0.0,
            "p_6000_10000": 0.0,
        }


